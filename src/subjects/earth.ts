const W = 240, H = 120;
let mask: Uint8Array | null = null;

function inside(ring: readonly (readonly [number, number])[], x: number, y: number): boolean {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]!;
    const [xj, yj] = ring[j]!;
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

function bake(): Uint8Array {
  const m = new Uint8Array(W * H);
  for (let y = 0; y < H; y++) {
    const lat = 90 - ((y + 0.5) / H) * 180;
    for (let x = 0; x < W; x++) {
      const lon = ((x + 0.5) / W) * 360 - 180;
      for (const ring of LAND) {
        if (inside(ring, lon, lat)) {
          m[y * W + x] = 1;
          break;
        }
      }
    }
  }
  return m;
}

/** 1 for land, 0 for sea. Longitude wraps; latitude clamps. */
export function isLand(lon: number, lat: number): number {
  mask ??= bake();
  const x = (((lon + 180) / 360) % 1 + 1) % 1;
  const y = Math.min(0.9999, Math.max(0, (90 - lat) / 180));
  return mask[((y * H) | 0) * W + ((x * W) | 0)]!;
}
